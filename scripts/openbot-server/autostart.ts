import { execFile } from "node:child_process";
import { access, chmod, mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

function quoteSystemd(value: string): string {
  if (!value || /[\r\n]/u.test(value)) throw new Error("Invalid systemd path.");
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function userServiceUnit(input: {
  readonly serverExecutable: string;
  readonly userDataDirectory: string;
  readonly runtimeDirectory: string;
}): string {
  return [
    "# Generated by OpenBot server CLI.",
    "[Unit]",
    "Description=OpenBot local identity server",
    "After=default.target network-online.target",
    "Wants=network-online.target",
    "StartLimitIntervalSec=0",
    "",
    "[Service]",
    "Type=simple",
    `ExecStart=${quoteSystemd(input.serverExecutable)} serve`,
    "WorkingDirectory=/",
    `Environment=OPENBOT_SERVER_USER_DATA=${quoteSystemd(input.userDataDirectory)}`,
    `Environment=OPENBOT_SERVER_RUNTIME_DIR=${quoteSystemd(input.runtimeDirectory)}`,
    "Restart=always",
    "RestartSec=5",
    "NoNewPrivileges=true",
    "PrivateTmp=true",
    "ProtectSystem=full",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}

export async function isManagedUserServiceInstalled(home = homedir()): Promise<boolean> {
  const path = join(home, ".config", "systemd", "user", "openbot-server.service");
  return (await readFile(path, "utf8").catch(() => "")).includes("Generated by OpenBot server CLI.");
}

function quoteShell(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

function quoteDesktop(value: string): string {
  if (!value || /[\r\n]/u.test(value)) throw new Error("Invalid desktop executable path.");
  return `"${value.replace(/[\\"`$]/gu, "\\$&")}"`;
}

export function trayAutostartEntry(executable: string, runtimeDirectory: string): string {
  return [
    "# Generated by OpenBot server CLI.",
    "[Desktop Entry]",
    "Type=Application",
    "Name=OpenBot Server Tray",
    "Comment=Show the local OpenBot server status.",
    `Exec=/usr/bin/env OPENBOT_SERVER_RUNTIME_DIR=${quoteDesktop(runtimeDirectory)} ${quoteDesktop(executable)} --openbot-server-tray`,
    "Terminal=false",
    "X-GNOME-Autostart-enabled=true",
    "",
  ].join("\n");
}

export async function installedOpenBotExecutable(home: string, environment: NodeJS.ProcessEnv): Promise<string | null> {
  const configured = environment.OPENBOT_APP_EXECUTABLE?.trim() || environment.APPIMAGE?.trim();
  if (configured) {
    await access(configured);
    return resolve(configured);
  }
  const dataHome = environment.XDG_DATA_HOME?.trim() || join(home, ".local", "share");
  try {
    const desktopEntry = await readFile(join(dataHome, "applications", "openbot.desktop"), "utf8");
    const command = desktopEntry
      .split("\n")
      .find((line) => line.startsWith("Exec="))
      ?.slice(5)
      ?.trim();
    if (!command) return null;
    const quoted = /^"((?:\\.|[^"\\])*)"/u.exec(command)?.[1];
    const executable = quoted ? quoted.replace(/\\(.)/gu, "$1") : command.split(/\s/u, 1)[0];
    if (!executable) return null;
    await access(executable);
    return resolve(executable);
  } catch {
    return null;
  }
}

export async function installUserService(input: {
  readonly serverExecutable: string;
  readonly userDataDirectory: string;
  readonly runtimeDirectory: string;
  readonly appExecutable?: string | null;
  readonly home?: string;
}): Promise<{
  readonly unitPath: string;
  readonly commandPath: string;
  readonly trayEntryPath: string | null;
  readonly lingerEnabled: boolean;
}> {
  const home = input.home ?? homedir();
  const unitPath = join(home, ".config", "systemd", "user", "openbot-server.service");
  const commandPath = join(home, ".local", "bin", "openbot-server-local");
  const wrapper = `#!/bin/sh\n# Generated by OpenBot server CLI.\nexec ${quoteShell(input.serverExecutable)} "$@"\n`;
  const [existingCommand, existingUnit] = await Promise.all([
    readFile(commandPath, "utf8").catch(() => ""),
    readFile(unitPath, "utf8").catch(() => ""),
  ]);
  const trayPath = input.appExecutable ? join(home, ".config", "autostart", "openbot-server-tray.desktop") : null;
  const existingEntry = trayPath ? await readFile(trayPath, "utf8").catch(() => "") : "";
  if (existingCommand && !existingCommand.includes("Generated by OpenBot server CLI.")) {
    throw new Error("The OpenBot server command already exists and was not changed.");
  }
  if (existingUnit && !existingUnit.includes("Generated by OpenBot server CLI.")) {
    throw new Error("The OpenBot server service already exists and was not changed.");
  }
  if (existingEntry && !existingEntry.includes("Generated by OpenBot server CLI.")) {
    throw new Error("The OpenBot server tray entry already exists and was not changed.");
  }
  await mkdir(dirname(commandPath), { recursive: true, mode: 0o700 });
  await writeFile(commandPath, wrapper, { encoding: "utf8", mode: 0o755 });
  await chmod(commandPath, 0o755);
  await mkdir(dirname(unitPath), { recursive: true, mode: 0o700 });
  await mkdir(input.userDataDirectory, { recursive: true, mode: 0o700 });
  await mkdir(input.runtimeDirectory, { recursive: true, mode: 0o700 });
  await writeFile(unitPath, userServiceUnit(input), { encoding: "utf8", mode: 0o600 });
  let trayEntryPath: string | null = null;
  if (input.appExecutable && trayPath) {
    const autostartDirectory = join(home, ".config", "autostart");
    trayEntryPath = trayPath;
    await mkdir(autostartDirectory, { recursive: true, mode: 0o700 });
    await writeFile(trayEntryPath, trayAutostartEntry(input.appExecutable, input.runtimeDirectory), {
      encoding: "utf8",
      mode: 0o644,
    });
  }
  await execFileAsync("systemctl", ["--user", "daemon-reload"], { timeout: 5_000 });
  await execFileAsync("systemctl", ["--user", "enable", "--now", "openbot-server.service"], { timeout: 15_000 });
  let lingerEnabled = false;
  try {
    const { stdout } = await execFileAsync("loginctl", ["show-user", "--property=Linger", "--value"], {
      timeout: 5_000,
    });
    lingerEnabled = stdout.trim() === "yes";
  } catch {
    // Some systems do not provide logind. The unit still starts with the user's session.
  }
  return {
    unitPath: resolve(unitPath),
    commandPath: resolve(commandPath),
    trayEntryPath: trayEntryPath ? resolve(trayEntryPath) : null,
    lingerEnabled,
  };
}

export async function removeUserService(home = homedir()): Promise<void> {
  const unitPath = join(home, ".config", "systemd", "user", "openbot-server.service");
  const unit = await readFile(unitPath, "utf8").catch(() => "");
  if (unit.includes("Generated by OpenBot server CLI.")) {
    await execFileAsync("systemctl", ["--user", "disable", "--now", "openbot-server.service"], {
      timeout: 15_000,
    }).catch(() => undefined);
    await unlink(unitPath).catch(() => undefined);
  }
  const trayPath = join(home, ".config", "autostart", "openbot-server-tray.desktop");
  const trayEntry = await readFile(trayPath, "utf8").catch(() => "");
  if (trayEntry.includes("Generated by OpenBot server CLI.")) await unlink(trayPath).catch(() => undefined);
  const commandPath = join(home, ".local", "bin", "openbot-server-local");
  const command = await readFile(commandPath, "utf8").catch(() => "");
  if (command.includes("Generated by OpenBot server CLI.")) await unlink(commandPath).catch(() => undefined);
  await execFileAsync("systemctl", ["--user", "daemon-reload"], { timeout: 5_000 }).catch(() => undefined);
}
